function startATM(app,src,~)
    function fileSaveText=fktFileSaveText(outputFolder4PZMFiles,baseName4PZMFiles,cC)
            fileSaveText = +...
                newline+"STRING:file:save " + """"+outputFolder4PZMFiles+baseName4PZMFiles+...
                newline+"STRING:file:save " + """"+outputFolder4PZMFiles+baseName4PZMFiles+"_Cycle"+cC+""""+...
                newline+"STRING:file:export " + """"+outputFolder4PZMFiles+baseName4PZMFiles+"_Cycle"+cC+".dat"+"""";
    end
    function ReadText = fktReadText(app,ampPos,ampNeg)
        if strcmp(app.ATMEcShiftDropDown.Value ,"M-polarity")
            PMseq = "0-XU---";
            writeAmp = ampNeg;
            readAmp = ampPos;
        elseif strcmp(app.ATMEcShiftDropDown.Value ,"N-polarity")
            PMseq= "1-YD---";
            writeAmp = ampPos;
            readAmp = ampNeg;
        end
        ReadText= ...
                "STRING:para:PM:pulseseq "+PMseq+newline+...
                "STRING:para:PM:waveform 1"+newline+...
                "STRING:para:PM:wam "+writeAmp+newline+...
                "STRING:para:PM:wpu 25e-9"+newline+...
                "STRING:para:PM:wri "+string(app.ATMfTreatEditField.Value*1000/4)+newline+...
                "STRING:para:PM:read 0.05"+newline+...
                "STRING:para:PM:amp "+readAmp+newline+...
                "STRING:para:PM:rri "+string(app.ATMfTreatEditField.Value*1000/4)+newline+...
                "STRING:para:PM:delayt 0.05"+newline+...
                "STRING:para:PM:curr "+app.ATMCuRangeDropDown.Value+newline;
    end
    function TreatText = fktTreatText(app,treataftread,Vamp,Bias,Reps)
        if strcmp(app.ATMEcShiftDropDown.Value ,"M-polarity")
            Vamp=-1*Vamp;
        end
        if treataftread % Everything has to be set again, since another mode was used.
            if Reps==1
                TreatText = ...
                    "STRING:para:PZM:freq "+ string(app.ATMfTreatEditField.Value*1000)+newline+...
                    "STRING:para:PZM:waveform triangle"+newline+...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions 1"+newline+...
                    "STRING:para:PZM:delayt 0.05"+newline+...
                    "STRING:para:PZM:single 1" + newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:unip 0" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline+...
                    "STRING:para:PZM:prep disabled" + newline+...
                    "STRING:para:PZM:curr "+ app.ATMCuRangeDropDown.Value+newline;
            elseif Reps ==2
                TreatText = ...
                    "STRING:para:PZM:freq "+ string(app.ATMfTreatEditField.Value*1000)+newline+...
                    "STRING:para:PZM:waveform triangle"+newline+...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions 1"+newline+...
                    "STRING:para:PZM:delayt 0.05"+newline+...
                    "STRING:para:PZM:single 1" + newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:unip 0" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline+...
                    "STRING:para:PZM:curr "+ app.ATMCuRangeDropDown.Value+newline;
            else 
                TreatText = ...
                    "STRING:para:PZM:freq "+ string(app.ATMfTreatEditField.Value*1000)+newline+...
                    "STRING:para:PZM:waveform triangle"+newline+...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions "+string(Reps)+newline+...
                    "STRING:para:PZM:delayt 0"+newline+...
                    "STRING:para:PZM:single 1" + newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:unip 0" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline+...
                    "STRING:para:PZM:curr "+ app.ATMCuRangeDropDown.Value+newline;
            end
        else % Base Parameters are already loaded. Only Bias, Reps, prep and Amp has to be adjusted
            if Reps==1
                TreatText = ...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions 1"+newline+...
                    "STRING:para:PZM:delayt 0.05"+newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline+...
                    "STRING:para:PZM:prep disabled" + newline;
            elseif Reps ==2
                TreatText = ...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions 1"+newline+...
                    "STRING:para:PZM:delayt 0.05"+newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline;
            else 
                TreatText = ...
                    "STRING:para:PZM:amp "+sprintf("%.2f", Vamp)+newline+...
                    "STRING:para:PZM:repetitions "+string(Reps)+newline+...
                    "STRING:para:PZM:delayt 0"+newline+...
                    "STRING:para:PZM:prep switching" + newline+...
                    "STRING:para:PZM:bia " + sprintf("%.2f",Bias)+ newline;
            end
        end
    end
    
    function giveAmpOverview(app, Text, VampArr, BiasArr)
            fig1=figure();
            ax1 = axes(fig1);
            plot(10.^(log10(1:str2double(app.ATMCyclesDropDown.Value))),BiasArr+VampArr)
            hold on
            plot(10.^(log10(1:str2double(app.ATMCyclesDropDown.Value))),BiasArr-VampArr)
            hold on
            plot(10.^(log10(1:str2double(app.ATMCyclesDropDown.Value))),BiasArr)
            ylabel("Amplitude [V]")
            xlabel("Cycle ")
            grid on;
            legend(["Pos. amp.", "Neg. amp.", "Bias"])
            xscale(ax1,'log');
    end
    
    updateMeasRunningStatus(app,src, true);
    


    measureText="STRING:sam:para:name "+app.SampleNameEditField.Value+newline + ...
                "STRING:sam:para:are "+app.PadAreaEditField.Value+newline + ...
                "STRING:sam:para:thi "+app.ThicknessEditField.Value+newline+newline;            

    clearAndModePZM=newline + ...
        "STRING:clear" + newline + ...
        "STRING:mode PZM" + newline;

    clearAndModePM=newline + ...
        "STRING:clear" + newline + ...
        "STRING:mode PM" + newline;
    
    if src==app.ATMStartMeasButton % The callback comes from the Start Meas. Button
        decadeSlopePosTreat = (app.ATMAmpnEditFieldPos.Value-app.ATMAmp0EditFieldPos.Value)/log10(str2double(app.ATMCyclesDropDown.Value)); % 
        decadeSlopeNegTreat = (app.ATMAmpnEditFieldNeg.Value-app.ATMAmp0EditFieldNeg.Value)/log10(str2double(app.ATMCyclesDropDown.Value)); % 
        VampPosTreat = log10(1:str2double(app.ATMCyclesDropDown.Value)).*decadeSlopePosTreat+app.ATMAmp0EditFieldPos.Value; %
        VampNegTreat = log10(1:str2double(app.ATMCyclesDropDown.Value)).*decadeSlopeNegTreat+app.ATMAmp0EditFieldNeg.Value; %
        VampTreat = (VampPosTreat-VampNegTreat)./2;
        biasTreat = VampPosTreat-VampTreat;

        cycleCounter = 0;

        scales = 10.^(1:log10(str2double(app.ATMCyclesDropDown.Value)));
        readCycles = unique([1,ceil(reshape((1:app.ATMReadperDecEditField.Value)'*(scales./app.ATMReadperDecEditField.Value),1,[]))]);
        treatModeAfterRead=false;
        readModeAfterTreat=true;
           
        %% % Text for first 100 cycles
        for idx=1:min(str2double(app.ATMCyclesDropDown.Value),100)
            cycleCounter=cycleCounter+1;
            if ismember(cycleCounter,readCycles)% If this cycle is a reading procedure...
                readModeAfterTreat=false;
                measureText = measureText + clearAndModePM;
                ReadParas = fktReadText(app,VampPosTreat(cycleCounter), VampNegTreat(cycleCounter));
                measureText = measureText + ...
                    newline+...
                    "// CYCLE "+cycleCounter+" READ PROCEDURE" + newline+...
                    ReadParas +...
                    "STRING:start " + newline+ ...
                    "%%IDLE_WAIT" + newline + newline+...
                    fktFileSaveText(app.ATMoutFolderEditField.Value,app.ATMbaseFileNameEditField.Value,cycleCounter)+newline+...
                    "%%IDLE_WAIT" + newline + newline+...
                    clearAndModePZM;
                    treatModeAfterRead=true;
            else % TREATMENT
                TreatParas=fktTreatText(app,treatModeAfterRead,VampTreat(cycleCounter),biasTreat(cycleCounter),1);
                treatModeAfterRead=false;
                measureText = measureText + newline+...
                    "// CYCLE "+cycleCounter+"  Amp: "+sprintf("%.2f",VampTreat(cycleCounter))+"  Bias: "+sprintf("%.2f",biasTreat(cycleCounter))+newline+ ...
                    TreatParas+...
                    "STRING:start " + newline+ ...
                    "%%IDLE_WAIT" + newline + newline;
                readModeAfterTreat=true;
            end
        end
        
        if ge(cycleCounter,str2double(app.ATMCyclesDropDown.Value))
            giveAmpOverview(app, measureText, VampTreat, biasTreat)
            return
        end

         %% % Text from 100 to NCycles
         incr=-1;
         while  cycleCounter<str2double(app.ATMCyclesDropDown.Value)
            oldIncr = incr;
            incr=min(10^ceil(log10(cycleCounter))/100,1000); % 10 if cycleCounter<1000, 100 if cycleCounter<1e4 and 1000 if cycleCounter >= 1e5
            if any(readCycles>cycleCounter & readCycles<= cycleCounter+incr) % There is a read Cycle coming!
                mask=readCycles>cycleCounter & readCycles<= cycleCounter+incr; % Creates an logic array, at which point exactly is the read cycle
                value=readCycles(mask); % The CycleNumber of the read cycle.
                reps=value-cycleCounter-1; % Evaluate how many Treatment repetitions are needed until the read cycle

                if reps==0 % Now is the read procedure
                    % READ PROCEDURE
                    cycleCounter=cycleCounter+1; % 
                    readModeAfterTreat=false; % this has gotten obsolete
                    measureText = measureText + clearAndModePM;
                    ReadParas = fktReadText(app,VampPosTreat(cycleCounter), VampNegTreat(cycleCounter));
                    measureText = measureText + ...
                        newline+...
                        "// CYCLE "+cycleCounter+" READ PROCEDURE" + newline+...
                        ReadParas +...
                        "STRING:start " + newline+ ...
                        "%%IDLE_WAIT" + newline + newline+...
                        fktFileSaveText(app.ATMoutFolderEditField.Value,app.ATMbaseFileNameEditField.Value,cycleCounter)+newline+...
                        "%%IDLE_WAIT" + newline + newline+...
                        clearAndModePZM;
                    treatModeAfterRead=true;
                else %if incr= 10 reps isbetween(reps,1,9), if incr= 100 reps isbetween(reps,1,99), if incr= 1000 reps isbetween(reps,1,999)...  
                    % TREATMENT with calculated repetitions
                    if reps==1
                        % DELAYT MUST BE MIN 0.05!
                        cycleCounter=cycleCounter+reps;
                        TreatParas=fktTreatText(app,treatModeAfterRead,VampTreat(cycleCounter),biasTreat(cycleCounter),reps);
                        treatModeAfterRead=false;
                        measureText = measureText + newline+...
                            "// CYCLE "+cycleCounter+"  Amp: "+sprintf("%.2f",VampTreat(cycleCounter))+"  Bias: "+sprintf("%.2f",biasTreat(cycleCounter))+newline+ ...
                            TreatParas+...
                            "STRING:start " + newline+ ...
                            "%%IDLE_WAIT" + newline + newline;
                        readModeAfterTreat=true;
                    elseif reps==2
                        % DELAY MUST BE MIN 0.05!!!
                        cycleCounter=cycleCounter+reps;
                        TreatParas=fktTreatText(app,treatModeAfterRead,VampTreat(cycleCounter),biasTreat(cycleCounter),reps-1);
                        treatModeAfterRead=false;
                        measureText = measureText + newline+...
                            "// CYCLE "+string(cycleCounter-1)+" AND "+string(cycleCounter)+"  Amp: "+sprintf("%.2f",VampTreat(cycleCounter))+"  Bias: "+sprintf("%.2f",biasTreat(cycleCounter))+newline+ ...
                            TreatParas+...
                            "STRING:start " + newline+ ...
                            "%%IDLE_WAIT" + newline + newline;
                        readModeAfterTreat=true;
                    else
                        % DELAY can be 0.
                        cylceOld=cycleCounter;
                        cycleCounter=cycleCounter+reps;
                        TreatParas=fktTreatText(app,treatModeAfterRead,VampTreat(cycleCounter),biasTreat(cycleCounter),reps-1);
                        treatModeAfterRead=false;
                        measureText = measureText + newline+...
                            "// CYCLE FROM "+string(cylceOld+1)+" TO "+string(cycleCounter)+"  Amp: "+sprintf("%.2f",VampTreat(cycleCounter))+"  Bias: "+sprintf("%.2f",biasTreat(cycleCounter))+newline+ ...
                            TreatParas+...
                            "STRING:start " + newline+ ...
                            "%%IDLE_WAIT" + newline + newline;
                        readModeAfterTreat=true;
                    end
                end
            else
                % No read procedure for next 10/100/1000 treatment cycles
                reps=incr;
                cylceOld=cycleCounter;
                cycleCounter=cycleCounter+incr;
                TreatParas=fktTreatText(app,treatModeAfterRead,VampTreat(cycleCounter),biasTreat(cycleCounter),reps-1);
                treatModeAfterRead=false;
                measureText = measureText + newline+...
                    "// CYCLE FROM "+string(cylceOld+1)+" TO "+string(cycleCounter)+"  Amp: "+sprintf("%.2f",VampTreat(cycleCounter))+"  Bias: "+sprintf("%.2f",biasTreat(cycleCounter))+newline+ ...
                    TreatParas+...
                    "STRING:start " + newline+ ...
                    "%%IDLE_WAIT" + newline + newline;
                readModeAfterTreat=true;
            end
         end
         if ge(cycleCounter,str2double(app.ATMCyclesDropDown.Value))
                    giveAmpOverview(app, measureText, VampTreat, biasTreat)
                    return
         end

        

    end
end